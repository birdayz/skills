// Command codexreview manages an OpenAI Codex (`codex` CLI) code review end to end:
// it invokes codex in a way that CANNOT hang, captures stdout/stderr, detects the
// real failure modes (quota/auth/empty), parses the ACK/NAK verdict, renders a
// PR comment from a Go template, and posts it with `gh`.
//
// Why a tool instead of a shell one-liner: `codex exec` blocks FOREVER if its stdin
// is left open (it waits to "read additional input from stdin"); a piped
// `codex exec ... | tail` hangs exactly this way. An exec.Cmd with Stdin == nil
// connects the child to /dev/null, so the hang is structurally impossible — and a
// hard context timeout + process-group kill is the backstop.
//
// Subcommands:
//
//	codexreview review  --base <branch|sha>   [flags]   # diff review of a branch/range
//	codexreview exec    --prompt "<steer>"    [flags]   # steered analysis (review can't take a prompt)
//
// Common flags: --model, --effort, --timeout, --post, --pr, --repo, --bypass-sandbox, --skill-url, --dir.
//
// Progress: a multi-minute run is NOT silent. The tool prints a heartbeat to stderr
// every --heartbeat seconds (default 15s) with elapsed time, tokens used, and
// turns/tool-calls so far, plus the latest activity line — so you NEVER need to pipe
// codex through `tail`/`grep` to "see if it's alive" (which also truncates the
// verdict). `-v/--verbose` streams codex's full live trace to stderr too. Metrics come
// from the real event stream: exec mode runs codex with `--json` (turn/usage events);
// review mode parses codex's human trace (tool-call markers + `tokens used`).
