const defaultSkillURL = "https://github.com/birdayz/skills/tree/master/codex-review"

// commentMarker is an invisible HTML comment appended to every posted comment so
// re-reviews can find-and-update the tool's PRIOR comment instead of spamming the PR
// (--supersede). It is template-independent (a custom --template still gets it).
const commentMarker = "<!-- codexreview:marker -->"

// commentTmpl is the PR-comment template — the same shape the skill documents, but
// rendered from data instead of an unquoted printf. Kept overridable via --template.
// The footer carries run stats (tokens · turns · tool-calls) so a reader can gauge how
// much work the review did at a glance.
const commentTmpl = "**Codex {{.Kind}}{{with .Duration}} in {{.}}{{end}}** · `{{.SHA}}`\n\n" +
	"---\n\n{{.Review}}\n\n---\n\n" +
	"`{{.Stats}}` · Generated by Codex {{.Version}} on {{.Model}} ({{.Effort}}) and [codex-review]({{.SkillURL}})"

// quotaRE matches the stderr signatures of a non-error EMPTY run: an exit-0 codex
// that produced no verdict because it was rate-limited, unauthenticated, or errored
// mid-stream. An empty review is NEVER a clean pass.
var quotaRE = regexp.MustCompile(`(?i)rate.?limit|quota|usage limit|429|too many|reached|not logged in|unauthor|stream error|error:|ContextWindowExceeded|UsageLimitExceeded`)

// verdictLineRE matches a VERDICT LINE — a line whose first word (after optional
// markdown bullets / emphasis / quote markers) is ACK / NAK / LGTM. Anchored to the
// line start so a verdict word buried mid-prose ("this isn't a clean ACK", "would
// NAK if…") does NOT count. Code spans are stripped before matching. The trailing
// `(?:\b|_)` also closes on a `_` so underscore-emphasis (`_NAK_`) matches, while a
// longer word (`NAKED`, `ACKNOWLEDGE`) still does not.
var verdictLineRE = regexp.MustCompile(`(?im)^[\s>*_#-]*(ACK|NAK|LGTM)(?:\b|_)`)

// fencedRE / inlineCodeRE strip fenced blocks and inline-code spans so a verdict
// word quoted inside code can never be read as the reviewer's verdict.
var (
	fencedRE     = regexp.MustCompile("(?s)```.*?```")
	inlineCodeRE = regexp.MustCompile("`[^`]*`")
)

// worktreePathRE matches an absolute path up to and including a `.claude/worktrees/<name>/`
// segment. It's the best-effort fallback in stripRepoPaths: a path codex emitted from inside
// a Claude Code worktree collapses to its repo-relative tail even when the exact work-tree
// root wasn't computed (symlink-resolved path, a stale toplevel). The `[^\s:]` classes keep
// a match inside one path token and short of the trailing `:line` suffix.
var worktreePathRE = regexp.MustCompile(`/[^\s:]*\.claude/worktrees/[^/\s:]+/`)

