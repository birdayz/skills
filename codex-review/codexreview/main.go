func main() {
	if len(os.Args) < 2 {
		usage(os.Stderr)
		os.Exit(2)
	}
	switch os.Args[1] {
	case "-h", "--help", "help":
		usage(os.Stdout)
		return
	case "review", "exec":
		// valid subcommand — fall through to parse its flags
	default:
		fmt.Fprintf(os.Stderr, "codexreview: unknown command %q\n\n", os.Args[1])
		usage(os.Stderr)
		os.Exit(2)
	}
	cfg := parseFlags(os.Args[1], os.Args[2:])

	// One Ctrl-C cleanly cancels the run (kills the whole codex process group).
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	res, err := run(ctx, cfg)
	if err != nil {
		fail("%v", err)
	}

	// Always surface the verdict + run stats + scratch paths for the caller.
	fmt.Printf("VERDICT: %s\n", res.Verdict)
	fmt.Printf("stats: %s · %s\n", res.Duration, res.metricsLine())
	fmt.Printf("review: %s  (%d lines)  ·  log: %s\n", res.ReviewPath, countLines(res.Review), res.LogPath)
	if res.Posted != "" {
		fmt.Printf("posted: %s\n", res.Posted)
	}
	// Echo the review prose so the caller (an agent) reads it inline.
	fmt.Printf("\n----- review -----\n%s\n", strings.TrimSpace(res.Review))
}

// parseFlags parses the flags for a validated mode ("review"|"exec"); main guarantees
// the mode before calling, so there's no mode check here.
func parseFlags(mode string, args []string) config {
	fs := flag.NewFlagSet("codexreview "+mode, flag.ExitOnError)
	cfg := config{mode: mode}
	// Mode-specific flags are registered ONLY for their mode, so `review -h` and
	// `exec -h` each show just the flags that apply (no cross-mode noise).
	switch mode {
	case "review":
		fs.StringVar(&cfg.base, "base", "", "base branch/sha to diff against (default = PR base or repo default)")
		fs.StringVar(&cfg.commit, "commit", "", "review a single commit instead of a range")
	case "exec":
		fs.StringVar(&cfg.prompt, "prompt", "", "the steering prompt (required)")
	}
	fs.StringVar(&cfg.model, "model", env("CODEX_REVIEW_MODEL", "gpt-5.6-sol"), "codex model (-m)")
	fs.StringVar(&cfg.effort, "effort", env("CODEX_REVIEW_REASONING_EFFORT", "ultra"), "reasoning effort (-c model_reasoning_effort=)")
	fs.DurationVar(&cfg.timeout, "timeout", 25*time.Minute, "hard wall-clock cap; the run is killed (process group) if exceeded")
	fs.BoolVar(&cfg.post, "post", false, "post the review as a PR comment via gh")
	fs.BoolVar(&cfg.supersede, "supersede", false, "with --post: post a NEW comment and COLLAPSE this tool's prior comments on the PR as 'outdated' (re-reviews keep one active comment + a folded history, no edit-in-place, no spam)")
	fs.BoolVar(&cfg.supersede, "update-last", false, "deprecated alias for --supersede")
	fs.StringVar(&cfg.pr, "pr", "", "PR number to post to (default: the current branch's PR)")
	fs.StringVar(&cfg.repo, "repo", "", "owner/name for gh (default: inferred from cwd)")
	fs.BoolVar(&cfg.bypass, "bypass-sandbox", false, "use --dangerously-bypass-approvals-and-sandbox instead of -s read-only (REQUIRED inside a nested sandbox/agent where bwrap can't nest; review writes nothing, so no edit risk)")
	fs.BoolVar(&cfg.keepPaths, "keep-paths", false, "keep codex's absolute file paths in the review (default: rewrite them to repo-relative so a posted comment doesn't leak the local repo/worktree path)")
	fs.StringVar(&cfg.skillURL, "skill-url", defaultSkillURL, "skill URL for the comment footer")
	fs.StringVar(&cfg.dir, "dir", "", "scratch dir for review.md/review.log (default: a per-repo+branch tmp dir)")
	fs.StringVar(&cfg.tmplFile, "template", "", "path to a Go text/template overriding the default PR-comment template")
	fs.StringVar(&cfg.codexBin, "codex", "codex", "codex binary")
	fs.StringVar(&cfg.ghBin, "gh", "gh", "gh binary")
	fs.BoolVar(&cfg.verbose, "v", false, "stream codex's full live trace to stderr (async runs only — floods a sync call's output)")
	fs.BoolVar(&cfg.verbose, "verbose", false, "alias for -v")
	fs.DurationVar(&cfg.heartbeat, "heartbeat", 15*time.Second, "progress heartbeat interval (elapsed · tokens · turns/tool-calls · activity); 0 disables")
	_ = fs.Parse(args)

	if mode == "exec" && strings.TrimSpace(cfg.prompt) == "" {
		fail("exec mode requires --prompt")
	}
	return cfg
}

